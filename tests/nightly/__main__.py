"""Run the nightly bug hunt and write the agent-ready bug list (see tests/nightly/__init__.py)."""

from __future__ import annotations

import argparse
import datetime as dt
import hashlib
import importlib.util
import json
import os
import re
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from tests.nightly import live  # noqa: E402

BUGS = ROOT / "bugs"


class Report:
    def __init__(self):
        self.bugs, self.timings, self.notes = [], {}, []

    def bug(self, area, title, repro, expected, actual, files=(), kind="bug"):
        bug_id = hashlib.sha1(f"{area}|{re.sub(r'[0-9.]+ ?s\\b', '', title)}".encode()).hexdigest()[:8]
        if any(b["id"] == bug_id for b in self.bugs):
            return
        self.bugs.append({"id": bug_id, "kind": kind, "area": area, "title": title, "repro": repro,
                          "expected": expected, "actual": str(actual)[:600], "files": list(files)})
        print(f"  BUG [{area}] {title}", flush=True)

    def timing(self, key, seconds):
        self.timings.setdefault(key, []).append(seconds)


def run_unit_tests(report: Report) -> None:
    """Unit tests (no database). Each failing test becomes a bug with its pytest node id."""
    cmd = [sys.executable, "-m", "pytest", "-q", "-p", "no:cacheprovider", "--ignore=tests/e2e",
           "--ignore=tests/nightly", "tests", "crossr_pipeline", "equibase_scraper", "ifha_scraper", "-rf"]
    env = {**os.environ, "DATABASE_URL": ""}
    out = subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True, env=env, timeout=1800)
    tail = (out.stdout or "").strip().splitlines()[-1:] or [""]
    report.notes.append(f"unit tests: {tail[0]}")
    for line in (out.stdout or "").splitlines():
        if line.startswith("FAILED "):
            node = line[7:].split(" - ")[0]
            report.bug("tests", f"unit test fails: {node}", f"python -m pytest -q {node}", "pass",
                       line[7:][:500], [node.split("::")[0]])
    if out.returncode not in (0, 1):
        report.bug("tests", "unit test run could not complete", " ".join(cmd), "exit 0 or 1",
                   f"exit {out.returncode}: {(out.stderr or '')[-400:]}", ["tests/"])


def run_audit(report: Report) -> None:
    """Database checks from scripts/data_audit.py (read-only)."""
    spec = importlib.util.spec_from_file_location("data_audit", ROOT / "scripts" / "data_audit.py")
    audit_mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(audit_mod)
    audit = audit_mod.Audit()
    audit_mod.run_db(audit)
    for r in audit.failed:
        report.bug("data", f"data audit: {r['check']} ({r['bad']} of {r['total']})",
                   "python3 scripts/data_audit.py --skip-api", f"at most the threshold ({r['note'] or 'see script'})",
                   "; ".join(r["examples"]), ["scripts/data_audit.py"])


def write(report: Report, started: float) -> Path:
    today = dt.date.today().isoformat()
    BUGS.mkdir(exist_ok=True)
    (BUGS / "inbox").mkdir(exist_ok=True)
    lines = [f"# Nightly bug report {today}", "",
             f"{len(report.bugs)} problem(s) found in {time.time() - started:.0f} s. "
             "Generated by `python -m tests.nightly`; fix on a branch, add a test, and don't push to `unified` "
             "without the owner's OK (see docs/PROJECT-BRIEFING.md).", ""]
    lines += [f"- {n}" for n in report.notes]
    if report.timings:
        lines += ["", "## Speed (seconds: median / worst; budgets in tests/nightly/live.py)", "",
                  "| Check | Median | Worst | Budget |", "|---|---|---|---|"]
        for key, vals in sorted(report.timings.items()):
            vals = sorted(vals)
            lines.append(f"| {key} | {vals[len(vals) // 2]:.2f} | {vals[-1]:.2f} | {live.BUDGETS.get(key, '')} |")
    for b in sorted(report.bugs, key=lambda b: (b["kind"] != "bug", b["area"])):
        lines += ["", f"## [{b['id']}] {b['title']}", f"- **Area:** {b['area']} ({b['kind']})",
                  f"- **Reproduce:** `{b['repro']}`", f"- **Expected:** {b['expected']}",
                  f"- **Actual:** {b['actual']}", f"- **Likely files:** {', '.join(b['files']) or '-'}"]
    text = "\n".join(lines) + "\n"
    out = BUGS / "inbox" / f"{today}.md"
    out.write_text(text)
    (BUGS / "latest.md").write_text(text)
    (BUGS / "inbox" / f"{today}.json").write_text(json.dumps({"date": today, "bugs": report.bugs,
                                                             "timings": report.timings, "notes": report.notes}, indent=1))
    return out


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--skip-unit", action="store_true")
    ap.add_argument("--skip-audit", action="store_true")
    ap.add_argument("--skip-live", action="store_true")
    ap.add_argument("--quick", action="store_true", help="fewer live samples")
    args = ap.parse_args()
    report, started = Report(), time.time()
    steps = [("unit tests", args.skip_unit, lambda: run_unit_tests(report)),
             ("data audit", args.skip_audit or not os.environ.get("DATABASE_URL"), lambda: run_audit(report)),
             ("live checks", args.skip_live, lambda: live.run(report, quick=args.quick))]
    for name, skip, fn in steps:
        if skip:
            report.notes.append(f"{name}: skipped")
            continue
        print(f"== {name}", flush=True)
        try:
            fn()
        except Exception as exc:  # a broken check is itself a bug to fix
            report.bug("nightly", f"{name} crashed", "python -m tests.nightly", "completes",
                       f"{exc.__class__.__name__}: {exc}", ["tests/nightly/"])
    path = write(report, started)
    print(f"{len(report.bugs)} problem(s); report: {path} (also bugs/latest.md)")
    sys.exit(1 if report.bugs else 0)


if __name__ == "__main__":
    main()
