"""Automated collection is intentionally off.

Maxson Cook (2026-11-05): all scrapers stay off. This switch stops new fetches
from Equibase, the Jockey Club, Pedigree Query, Racing Post, NYRA, Keeneland,
Fasig-Tipton, BloodHorse, IFHA, and the stallion-news crawl. Rows already in
the database stay where they are. Nothing here drops a table or deletes a file
of collected data.

A person turns collection back on by setting COLLECTION_ENABLED to True.
Do not flip it from a scheduled job.

Jobs that only run as launchd on the Mac (~/Crossr-pipeline) are not stopped
by a change in this repo. Unload those plists on the Mac. See
LAUNCHD_COLLECTION_LABELS and MAC_ONLY_COLLECTION_LABELS.
"""

from __future__ import annotations

# Intentionally off. Leave this False until Maxson says scrapers may run.
COLLECTION_ENABLED = False

# Written by install-launchd before this switch. install-launchd no longer writes them.
LAUNCHD_COLLECTION_LABELS = (
    "com.crossr.pipeline.scrape",          # Equibase hourly: pedigrees, dams, race records, catalogs
    "com.crossr.pipeline.racing-post",     # Racing Post stud-fee pages
    "com.crossr.pipeline.mares-bred",      # Jockey Club Report of Mares Bred
    "com.crossr.pipeline.entries",         # NYRA published entries
    "com.crossr.pipeline.stallion-news",   # Thoroughbred Daily News crawl
)

# Not generated by this repo. They exist only as LaunchAgents on the Mac.
MAC_ONLY_COLLECTION_LABELS = (
    "com.maxsoncook.pq.fetch-gsw",         # Pedigree Query fetch
    "com.maxsoncook.pq.fetch-watchdog",    # restarts the Pedigree Query fetch
)

OFF_NOTICE = (
    "Automated collection is intentionally off "
    "(crossr_pipeline/collection.py: COLLECTION_ENABLED = False). "
    "Collected data is unchanged."
)


def refuse_if_off(job: str) -> None:
    """Stop a collection job before it fetches.

    Exits 0 so a launchd agent that is still loaded does not treat the stop
    as a crash and start again a minute later. The agent is not unloaded.
    """
    if COLLECTION_ENABLED:
        return
    print(f"{job} is off. {OFF_NOTICE}", flush=True)
    raise SystemExit(0)
